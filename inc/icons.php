if (!function_exists('bootscore_icon')) {
  /**
   * Outputs or returns a filterable, sanitized SVG icon.
   *
   * @param string $name Icon name, matches a key in bootscore_icon_defaults() and the bootscore/icon/{name} filter.
   * @param bool   $echo Whether to echo the icon (default) or return it as a string.
   * @return string|void Icon markup when $echo is false, otherwise void.
   */
  function bootscore_icon($name, $echo = true) {

    $icon = wp_kses(
      apply_filters('bootscore/icon/' . $name, bootscore_icon_defaults($name)),
      bootscore_kses_allowed_svg( wp_kses_allowed_html('post') )
    );

    if ($echo) {
      echo $icon;
      return;
    }

    return $icon;

  }
